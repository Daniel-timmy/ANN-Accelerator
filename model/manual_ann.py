import math
import pandas as pd

def sigmoid(x):
  return 1 / (1 + math.exp(-x))


def predict_manual(input, W1, b1, W2, b2):
  # 1. Hidden layer calculation (dot product + bias)
  hidden_layer = []
  weighted_sum = []
  for j in range(len(W1[0])):  # for each neuron in hidden layer
    products = []
    for i in range(len(input)):
      product = input[i] * W1[i][j]
      # print(f"Hidden neuron {j}, input {i}: {input[i]} * weight {W1[i][j]} = {product}")
      products.append(product)
    s = sum(products) + b1[j]
    weighted_sum.append(s)
    hidden_layer.append(sigmoid(s))
    # print("Neuron", j, "in hidden layer:", hidden_layer[j])  # Debugging line
  # print("Weighted sums for hidden layer:", weighted_sum)  # Debugging line
  print("Hidden layer outputs:", hidden_layer)  # Debugging line
  # 2. Output layer calculation (dot product + bias)
  output_layer = []
  for k in range(len(W2[0])):  # for each neuron in output layer
    s = sum(hidden_layer[j] * W2[j][k] for j in range(len(hidden_layer))) + b2[k]
    print(f"Output neuron {k}: weighted sum = {s}")  # Debugging line
    output_layer.append(sigmoid(s))

  return output_layer



